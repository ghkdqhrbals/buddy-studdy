    @Test
    fun `guarded delete rejects changed scope then cascades only nodes while retaining question and voice history`(): Unit = runBlocking {
        insertStudy(10, "Root")
        insertStudy(11, "Redis", parentId = 10)
        execute("insert into questions(id, study_id, answer, score) values (81, 11, 'Original typed answer', 85)")
        execute("insert into voice_tutor_sessions(id, study_id) values ('synthetic-prior-session', 11)")
        execute("insert into voice_study_learning_records(id, session_id, study_id, topic, difficulty, answer, score) values (91, 'synthetic-prior-session', 11, 'Redis', 3, 'Original spoken answer', 85)")

        val changed = runCatching { transaction { service.deleteStudy(principal, 10, listOf(10L)) } }.exceptionOrNull() as ApiException
        assertThat(changed.code).isEqualTo(ApiErrorCode.STUDY_TREE_CHANGED)
        assertThat(repository.findAllByUserId(7)).hasSize(2)
        transaction { service.deleteStudy(principal, 10, listOf(11L, 10L)) }

        assertThat(repository.findAllByUserId(7)).isEmpty()
        val question = database.sql("select study_id, answer, score from questions where id = 81").fetch().one().awaitSingle()
        assertThat(question["study_id"]).isNull()
        assertThat(question["answer"]).isEqualTo("Original typed answer")
        assertThat((question["score"] as Number).toInt()).isEqualTo(85)
        val session = database.sql("select study_id from voice_tutor_sessions where id = 'synthetic-prior-session'").fetch().one().awaitSingle()
        assertThat(session["study_id"]).isNull()
        val voice = database.sql("select study_id, topic, difficulty, answer, score from voice_study_learning_records where id = 91").fetch().one().awaitSingle()
        assertThat((voice["study_id"] as Number).toLong()).isEqualTo(11)
        assertThat(voice["topic"]).isEqualTo("Redis")
        assertThat((voice["difficulty"] as Number).toInt()).isEqualTo(3)
        assertThat(voice["answer"]).isEqualTo("Original spoken answer")
        assertThat((voice["score"] as Number).toInt()).isEqualTo(85)
        Mockito.verifyNoInteractions(questions, stats, localizations)
    }

    @Test
    fun `subtree traversal rejects mixed ownership and cycles and returns one bounded overflow ID`(): Unit = runBlocking {
        insertStudy(10, "Root")
        insertStudy(11, "Child", parentId = 10, userId = 99)
        assertThat(transaction {
            repository.lockMutationOwner(7)
            listOf(repository.findSubtreeIdsForMutation(7, 10, 129))
        }.single()).isNull()
        execute("update studies set user_id = 7 where id = 11")
        execute("update studies set parent_study_id = 11 where id = 10")
        assertThat(transaction {
            repository.lockMutationOwner(7)
            listOf(repository.findSubtreeIdsForMutation(7, 10, 129))
        }.single()).isNull()
        execute("update studies set parent_study_id = null where id = 10")
        insertStudy(1000, "Large root")
        for (id in 1001L..1130L) insertStudy(id, "Child $id", parentId = 1000)
        val bounded = transaction {
            repository.lockMutationOwner(7)
            requireNotNull(repository.findSubtreeIdsForMutation(7, 1000, 129))
        }
        assertThat(bounded).hasSize(129)
        assertThat(bounded.first()).isEqualTo(1000)
        assertThat(bounded).doesNotHaveDuplicates()
    }

    @Test
    fun `a child created under the common owner lock makes an earlier delete confirmation stale`(): Unit = runBlocking {
        insertStudy(10, "Root")
        val childInserted = CompletableDeferred<Unit>()
        val releaseFirst = CompletableDeferred<Unit>()
        val secondEntered = CompletableDeferred<Unit>()
        val first = async(Dispatchers.IO) {
            transaction {
                val child = service.createStudyTopic(principal, 10, CreateStudyTopicCommand(topic = "New child"))
                childInserted.complete(Unit)
                releaseFirst.await()
                child
            }
        }
        try {
            withTimeout(5_000) { childInserted.await() }
            val second = async(Dispatchers.IO) {
                runCatching {
                    transaction {
                        secondEntered.complete(Unit)
                        service.deleteStudy(principal, 10, listOf(10L))
                    }
                }
            }
            withTimeout(5_000) { secondEntered.await() }
            assertThat(withTimeoutOrNull(100) { second.await() }).isNull()
            releaseFirst.complete(Unit)
            withTimeout(5_000) { first.await() }
            val stale = withTimeout(5_000) { second.await() }.exceptionOrNull() as ApiException
            assertThat(stale.code).isEqualTo(ApiErrorCode.STUDY_TREE_CHANGED)
        } finally {
            releaseFirst.complete(Unit)
        }
        assertThat(repository.findAllByUserId(7)).hasSize(2)
        assertThat(repository.findAllByUserId(7).map { it.topic }).containsExactlyInAnyOrder("Root", "New child")
    }

    private suspend fun <T : Any> transaction(block: suspend () -> T): T =
        requireNotNull(transactions.executeAndAwait { block() })

    private suspend fun execute(sql: String): Unit {
        database.sql(sql).fetch().rowsUpdated().awaitSingle()
    }

    private suspend fun insertStudy(id: Long, topic: String, parentId: Long? = null, userId: Long = 7): Unit {
        var insert = database.sql(
            "insert into studies(id, user_id, parent_study_id, topic, created_at, updated_at) values (:id, :userId, :parentId, :topic, :created, :updated)",
        ).bind("id", id).bind("userId", userId).bind("topic", topic).bind("created", now.utc()).bind("updated", now.utc())
        insert = parentId?.let { insert.bind("parentId", it) } ?: insert.bindNull("parentId", java.lang.Long::class.java)
        insert.fetch().rowsUpdated().awaitSingle()
    }

    private fun Instant.utc(): LocalDateTime = LocalDateTime.ofInstant(this, ZoneOffset.UTC)

    @ReadingConverter
    private object ReadUtcInstant : Converter<LocalDateTime, Instant> {
        override fun convert(source: LocalDateTime): Instant = source.toInstant(ZoneOffset.UTC)
    }

    @WritingConverter
    private object WriteUtcInstant : Converter<Instant, LocalDateTime> {
        override fun convert(source: Instant): LocalDateTime = LocalDateTime.ofInstant(source, ZoneOffset.UTC)
    }
