@Timeout(15)
class StudyRepositoryMetadataPatchTest {
    private val now = Instant.parse("2026-09-01T01:00:00Z")
    private val connections = ConnectionFactories.get(
        "r2dbc:h2:mem:///study-metadata-${UUID.randomUUID()};MODE=MySQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=5000",
    )
    private val database = DatabaseClient.create(connections)
    private val transactions = TransactionalOperator.create(R2dbcTransactionManager(connections))
    private val repository: StudyRepository
    private val questions = Mockito.mock(QuestionPort::class.java)
    private val stats = Mockito.mock(QuestionStatsPort::class.java)
    private val localizations = Mockito.mock(ContentLocalizationPort::class.java)
    private val service: StudySyncService
    private val principal = Principal(7, "metadata-fixture", 70, anonymous = false)

    init {
