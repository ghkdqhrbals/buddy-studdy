    @Test
    fun `partial SQL preserves scheduling preferences tree identity and history while returning the current row`(): Unit = runBlocking {
        insertStudy(10, "Root")
        insertStudy(11, "Redis", parentId = 10)
        database.sql(
            """
            update studies set sort_order = 8, difficulty_level = 3, interval_minutes = 47,
                enabled = true, active_for_questions = false, notification_sound = 'bell.caf',
                custom_prompt = 'Keep this preference', openai_model = 'chosen-model', max_history_count = 231,
                next_due_at = :due, schedule_claimed_until = :claim, last_sent_at = :sent, last_error = 'Existing error'
            where id = 11
            """.trimIndent(),
        ).bind("due", now.utc()).bind("claim", now.plusSeconds(35).utc()).bind("sent", now.minusSeconds(600).utc())
            .fetch().rowsUpdated().awaitSingle()
        val before = requireNotNull(repository.findByIdAndUserId(11, 7))
        val renamed = transaction { service.updateStudy(principal, 11, UpdateStudyCommand(topic = " Redis Streams ")) }
        assertThat(renamed.topic).isEqualTo("Redis Streams")
        assertThat(renamed.difficultyLevel).isEqualTo(3)
        val changed = transaction { service.updateStudy(principal, 11, UpdateStudyCommand(difficultyLevel = 7)) }
        val after = requireNotNull(repository.findByIdAndUserId(11, 7))

        assertThat(changed.id).isEqualTo(11)
        assertThat(changed.parentStudyId).isEqualTo(10)
        assertThat(changed.nextDueAt).isEqualTo(now)
        assertThat(after).usingRecursiveComparison()
            .ignoringFields("topic", "difficultyLevel", "updatedAt", "version")
            .isEqualTo(before)
        assertThat(after.topic).isEqualTo("Redis Streams")
        assertThat(after.difficultyLevel).isEqualTo(7)
        Mockito.verifyNoInteractions(questions, stats, localizations)
    }

    @Test
    fun `missing and foreign updates return null while an identical repeated patch still reselects the owned row`(): Unit = runBlocking {
        insertStudy(11, "Redis")
        insertStudy(99, "Private", userId = 99)

        assertThat(transaction { listOf(repository.updateTopicMetadata(11, 7, "Redis", null, now)) }.single()).isNotNull()
        assertThat(transaction { listOf(repository.updateTopicMetadata(11, 7, "Redis", null, now)) }.single()).isNotNull()
        assertThat(transaction { listOf(repository.updateTopicMetadata(99, 7, "Wrong owner", 1, now)) }.single()).isNull()
        assertThat(transaction { listOf(repository.updateTopicMetadata(999, 7, "Missing", 1, now)) }.single()).isNull()
        assertThat(repository.findByIdAndUserId(99, 99)?.topic).isEqualTo("Private")
        assertThat(repository.findByIdAndUserId(11, 7)?.updatedAt).isEqualTo(now)
        assertThat(transaction { repository.lockMutationOwner(123456) }).isFalse()
    }

    @Test
