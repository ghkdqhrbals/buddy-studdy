        val mapping = RelationalMappingContext().also { it.setSimpleTypeHolder(conversions.simpleTypeHolder) }
        repository = StudyRepository(
            R2dbcEntityTemplate(database, MySqlDialect.INSTANCE, MappingR2dbcConverter(mapping, conversions)),
            BuddyStudyProperties(),
        )
        service = StudySyncService(repository, questions, stats, localizations)
    }

